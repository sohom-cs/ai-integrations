import { createHash } from 'crypto';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';

const STRANDS_FAILURE_CONVERTER = require.resolve('./failure-converter');
const composedPaths = new Map<string, string>();
let composedDir: string | undefined;

/**
 * The `failureConverterPath` that {@link StrandsPlugin} sets on a client or worker. With no caller
 * converter it is Strands' own module. With one, it is a generated module, written once per process
 * to a private temporary directory, that exports
 * `composeFailureConverter(require(<caller path>).failureConverter)`. The worker bundles it into
 * workflow code like any other converter module.
 */
export function failureConverterPathFor(callerPath: string | undefined): string {
  if (callerPath === undefined || callerPath === STRANDS_FAILURE_CONVERTER) {
    return STRANDS_FAILURE_CONVERTER;
  }
  if (composedDir !== undefined && path.dirname(callerPath) === composedDir) {
    // The plugin ran before on these options, for example on both the connection and the worker.
    return callerPath;
  }
  // Resolve the caller's path as the SDK does when it loads it.
  const resolved = require.resolve(callerPath, { paths: [path.dirname(require.resolve('@temporalio/common'))] });
  let composedPath = composedPaths.get(resolved);
  if (composedPath === undefined) {
    if (composedDir === undefined) {
      const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'temporal-strands-agents-'));
      process.once('exit', () => fs.rmSync(dir, { recursive: true, force: true }));
      composedDir = dir;
    }
    const source = [
      "'use strict';",
      "// Generated by @temporalio/strands-agents: Strands' failure converter in front of the caller's.",
      `const { composeFailureConverter } = require(${JSON.stringify(STRANDS_FAILURE_CONVERTER)});`,
      `exports.failureConverter = composeFailureConverter(require(${JSON.stringify(resolved)}).failureConverter);`,
      '',
    ].join('\n');
    const hash = createHash('sha256').update(resolved).digest('hex').slice(0, 16);
    composedPath = path.join(composedDir, `failure-converter-${hash}.js`);
    fs.writeFileSync(composedPath, source);
    composedPaths.set(resolved, composedPath);
  }
  return composedPath;
}
